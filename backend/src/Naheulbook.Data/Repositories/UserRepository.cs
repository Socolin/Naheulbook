#pragma warning disable 8619
using Microsoft.EntityFrameworkCore;
using Naheulbook.Data.EntityFrameworkCore.DbContexts;
using Naheulbook.Data.EntityFrameworkCore.Entities;

namespace Naheulbook.Data.Repositories;

public interface IUserRepository : IRepository<UserEntity>
{
    Task<UserEntity?> GetByUsernameAsync(string username, CancellationToken cancellationToken = default);
    Task<UserEntity?> GetByFacebookIdAsync(string facebookId, CancellationToken cancellationToken = default);
    Task<UserEntity?> GetByGoogleIdAsync(string googleId, CancellationToken cancellationToken = default);
    Task<UserEntity?> GetByMicrosoftIdAsync(string microsoftId, CancellationToken cancellationToken = default);
    Task<List<UserEntity>> SearchUsersAsync(string filter, CancellationToken cancellationToken = default);
    Task<List<UserEntity>> SearchByIdentifiersAsync(UserIdentifiersFilter filter, CancellationToken cancellationToken = default);

    /// <summary>
    /// Delete the user and everything it owns, in a single transaction:
    /// <list type="bullet">
    /// <item>the groups it is the GM of, with everything in them (NPCs, monsters and their items, loots, fights, events…).
    /// The characters of the other players are kept, they are only removed from the group.</item>
    /// <item>its characters, with everything attached to them</item>
    /// <item>its map layers and their markers. Links from other markers targeting them only lose their target marker.</item>
    /// <item>its access tokens and sessions</item>
    /// </list>
    /// The item templates it created are kept, without owner.
    /// </summary>
    Task DeleteWithOwnedDataAsync(int userId, CancellationToken cancellationToken = default);
}

public record UserIdentifiersFilter(string? Username, string? FacebookId, string? GoogleId, string? MicrosoftId, string? TwitterId)
{
    public bool IsEmpty => Username == null && FacebookId == null && GoogleId == null && MicrosoftId == null && TwitterId == null;
}

public class UserRepository(NaheulbookDbContext naheulbookDbContext) : Repository<UserEntity, NaheulbookDbContext>(naheulbookDbContext), IUserRepository
{
    public Task<UserEntity?> GetByUsernameAsync(string username, CancellationToken cancellationToken = default)
    {
        return Context.Users
            .Where(u => u.Username == username)
            .SingleOrDefaultAsync(cancellationToken);
    }

    public Task<UserEntity?> GetByFacebookIdAsync(string facebookId, CancellationToken cancellationToken = default)
    {
        return Context.Users
            .Where(u => u.FbId == facebookId)
            .SingleOrDefaultAsync(cancellationToken);
    }

    public Task<UserEntity?> GetByGoogleIdAsync(string googleId, CancellationToken cancellationToken = default)
    {
        return Context.Users
            .Where(u => u.GoogleId == googleId)
            .SingleOrDefaultAsync(cancellationToken);
    }

    public Task<UserEntity?> GetByMicrosoftIdAsync(string microsoftId, CancellationToken cancellationToken = default)
    {
        return Context.Users
            .Where(u => u.MicrosoftId == microsoftId)
            .SingleOrDefaultAsync(cancellationToken);
    }

    public Task<List<UserEntity>> SearchUsersAsync(string filter, CancellationToken cancellationToken = default)
    {
        return Context.Users
            .Where(u => u.DisplayName != null && u.DisplayName.ToLower().Contains(filter.ToLower()))
            .Where(u => u.ShowInSearchUntil > DateTime.UtcNow)
            .Take(10)
            .ToListAsync(cancellationToken);
    }

    public Task<List<UserEntity>> SearchByIdentifiersAsync(UserIdentifiersFilter filter, CancellationToken cancellationToken = default)
    {
        var query = Context.Users.AsQueryable();
        if (filter.Username != null)
            query = query.Where(u => u.Username == filter.Username);
        if (filter.FacebookId != null)
            query = query.Where(u => u.FbId == filter.FacebookId);
        if (filter.GoogleId != null)
            query = query.Where(u => u.GoogleId == filter.GoogleId);
        if (filter.MicrosoftId != null)
            query = query.Where(u => u.MicrosoftId == filter.MicrosoftId);
        if (filter.TwitterId != null)
            query = query.Where(u => u.TwitterId == filter.TwitterId);

        return query
            .OrderBy(u => u.Id)
            .Take(50)
            .ToListAsync(cancellationToken);
    }

    public async Task DeleteWithOwnedDataAsync(int userId, CancellationToken cancellationToken = default)
    {
        // Raw SQL: the deletes generated by `ExecuteDeleteAsync` (`DELETE FROM t AS a`) are not supported by MariaDB.
        // The retrying execution strategy does not allow user initiated transactions outside of it.
        var strategy = Context.Database.CreateExecutionStrategy();
        await strategy.ExecuteAsync(async ct =>
        {
            await using var transaction = await Context.Database.BeginTransactionAsync(ct);

            await DeleteGroupsOfMasterAsync(userId, ct);
            await DeleteCharactersOfOwnerAsync(userId, ct);
            await DeleteMapLayersOfUserAsync(userId, ct);

            await Context.Database.ExecuteSqlAsync($"DELETE FROM `user_access_token` WHERE `userId` = {userId}", ct);
            // `user_sessions` are deleted by cascade, `item_templates.sourceuserid` is set to null
            await Context.Database.ExecuteSqlAsync($"DELETE FROM `users` WHERE `id` = {userId}", ct);

            await transaction.CommitAsync(ct);
        }, cancellationToken);
    }

    private async Task DeleteGroupsOfMasterAsync(int userId, CancellationToken cancellationToken)
    {
        // `characters.groupId` is ON DELETE CASCADE: keep the characters of the other players
        await Context.Database.ExecuteSqlAsync($"""
            UPDATE `characters` SET `groupId` = NULL
            WHERE `groupId` IN (SELECT `id` FROM `groups` WHERE `masterId` = {userId}) AND `userId` <> {userId}
            """, cancellationToken);

        // `items.monsterid` is ON DELETE SET NULL, the items would be left without owner
        await Context.Database.ExecuteSqlAsync($"""
            DELETE FROM `items`
            WHERE `monsterid` IN (SELECT `id` FROM `monsters` WHERE `group` IN (SELECT `id` FROM `groups` WHERE `masterId` = {userId}))
            """, cancellationToken);

        // `npcs.groupId` is ON DELETE RESTRICT
        await Context.Database.ExecuteSqlAsync($"""
            DELETE FROM `npcs` WHERE `groupId` IN (SELECT `id` FROM `groups` WHERE `masterId` = {userId})
            """, cancellationToken);

        // Avoid having the cascade delete of the loots updating the groups being deleted
        await Context.Database.ExecuteSqlAsync($"UPDATE `groups` SET `combatlootid` = NULL WHERE `masterId` = {userId}", cancellationToken);

        // Events, fights, history, invites, loots (and their items), merchants, monsters and quests are deleted by cascade
        await Context.Database.ExecuteSqlAsync($"DELETE FROM `groups` WHERE `masterId` = {userId}", cancellationToken);
    }

    private async Task DeleteCharactersOfOwnerAsync(int userId, CancellationToken cancellationToken)
    {
        // These tables are ON DELETE RESTRICT on `characters`
        await Context.Database.ExecuteSqlAsync($"DELETE FROM `characters_aptitudes` WHERE `characterId` IN (SELECT `id` FROM `characters` WHERE `userId` = {userId})", cancellationToken);
        await Context.Database.ExecuteSqlAsync($"DELETE FROM `characters_handicaps` WHERE `characterId` IN (SELECT `id` FROM `characters` WHERE `userId` = {userId})", cancellationToken);
        await Context.Database.ExecuteSqlAsync($"DELETE FROM `characters_masteries` WHERE `characterId` IN (SELECT `id` FROM `characters` WHERE `userId` = {userId})", cancellationToken);
        await Context.Database.ExecuteSqlAsync($"DELETE FROM `characters_special_attacks` WHERE `characterId` IN (SELECT `id` FROM `characters` WHERE `userId` = {userId})", cancellationToken);
        await Context.Database.ExecuteSqlAsync($"DELETE FROM `characters_spell_books` WHERE `characterId` IN (SELECT `id` FROM `characters` WHERE `userId` = {userId})", cancellationToken);
        await Context.Database.ExecuteSqlAsync($"DELETE FROM `characters_talents` WHERE `characterId` IN (SELECT `id` FROM `characters` WHERE `userId` = {userId})", cancellationToken);
        await Context.Database.ExecuteSqlAsync($"DELETE FROM `character_jobs` WHERE `characterId` IN (SELECT `id` FROM `characters` WHERE `userId` = {userId})", cancellationToken);

        // History, modifiers, skills, specialities, invites and items are deleted by cascade
        await Context.Database.ExecuteSqlAsync($"DELETE FROM `characters` WHERE `userId` = {userId}", cancellationToken);
    }

    private async Task DeleteMapLayersOfUserAsync(int userId, CancellationToken cancellationToken)
    {
        // `map_marker_links` and `map_markers` are ON DELETE RESTRICT
        await Context.Database.ExecuteSqlAsync($"""
            DELETE FROM `map_marker_links`
            WHERE `mapMarkerId` IN (SELECT m.`id` FROM `map_markers` m JOIN `map_layers` l ON l.`id` = m.`layerId` WHERE l.`userId` = {userId})
            """, cancellationToken);
        // Links of other markers still point to the map, only without a specific marker
        await Context.Database.ExecuteSqlAsync($"""
            UPDATE `map_marker_links` SET `targetMapMarkerId` = NULL
            WHERE `targetMapMarkerId` IN (SELECT m.`id` FROM `map_markers` m JOIN `map_layers` l ON l.`id` = m.`layerId` WHERE l.`userId` = {userId})
            """, cancellationToken);
        await Context.Database.ExecuteSqlAsync($"""
            DELETE FROM `map_markers` WHERE `layerId` IN (SELECT `id` FROM `map_layers` WHERE `userId` = {userId})
            """, cancellationToken);
        await Context.Database.ExecuteSqlAsync($"DELETE FROM `map_layers` WHERE `userId` = {userId}", cancellationToken);
    }
}
